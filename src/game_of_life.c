#include <ncurses.h>   // Библиотека для работы с консольным интерфейсом
#include <stdio.h>     // Стандартный ввод-вывод
#include <unistd.h>    // Для usleep()

#define W 80           // Ширина игрового поля
#define H 25           // Высота игрового поля

// Инициализация библиотеки ncurses
void init_game() {
    initscr();                 // Инициализация экрана
    cbreak();                  // Посимвольный ввод без ожидания Enter
    noecho();                  // Не отображать вводимые символы
    nodelay(stdscr, TRUE);     // Неблокирующий ввод
    curs_set(0);               // Скрыть курсор
    keypad(stdscr, TRUE);      // Включить обработку специальных клавиш
}

// Чтение начального состояния поля из stdin
// Чтение начального состояния поля из stdin
void input_grid(int grid[H][W]) {
    char c;           // Текущий символ
    int i = 0, j = 0; // Координаты в сетке
    
    while (i < H && (c = getchar()) != EOF) {
        if (c == '\n') {        // Конец строки
            i++;                // Переход на следующую строку
            j = 0;              // Сброс позиции в строке
        } else {
            if (j < W) {        // Если не вышли за ширину поля
                // Символы, которые считаются "живыми" клетками
                if (c == '1' || c == 'O' || c == 'o' || c == '*')
                    grid[i][j] = 1; // Живая клетка
                else
                    grid[i][j] = 0; // Мертвая клетка
                j++;                // Следующий столбец
            }
        }
    }
}

/* Обновленная функция отрисовки с выводом интерфейса */
void draw(int grid[H][W], int speed) {
    clear();  // Очистка экрана
    
    /* Отрисовка игрового поля */
    for (int i = 0; i < H; i++) {
        for (int j = 0; j < W; j++) {
            if (grid[i][j]) 
                mvaddch(i, j, 'O' | A_BOLD); // Живая клетка жирным символом 'O'
        }
    }
    
    /* Отрисовка интерфейса под полем */
    mvprintw(H, 0, "Controls: [A] Speed Up  [Z] Slow Down  [SPACE, Q] Exit");
    mvprintw(H + 1, 0, "Current Delay: %d mcs", speed);  // Текущая задержка
    refresh();  // Обновление экрана
}

// Подсчет живых соседей для клетки (r, c)
int count_neib(int grid[H][W], int r, int c) {
    int count = 0;  // Счетчик соседей
    
    // Проверяем 8 соседних клеток
    for (int i = -1; i <= 1; i++) {
        for (int j = -1; j <= 1; j++) {
            // Тороидальная геометрия - края соединены
            int row = (r + i + H) % H;
            int col = (c + j + W) % W;
            
            // Добавляем состояние соседа, если это не сама клетка
            if (!(i == 0 && j == 0)) {
                count += grid[row][col];
            }
        }
    }
    return count;
}

// Пересчет следующего поколения
void recalc(int grid[H][W], int next[H][W]) {
    // Вычисляем новое состояние для каждой клетки
    for (int i = 0; i < H; i++) {
        for (int j = 0; j < W; j++) {
            int n = count_neib(grid, i, j);  // Количество соседей
            
            if (grid[i][j])                     // Если клетка жива
                next[i][j] = (n == 2 || n == 3); // Остается живой при 2 или 3 соседях
            else                                // Если клетка мертва
                next[i][j] = (n == 3);           // Оживает при 3 соседях
        }
    }
    
    // Копируем новое состояние в основной массив
    for (int i = 0; i < H; i++)
        for (int j = 0; j < W; j++) 
            grid[i][j] = next[i][j];
}

// Обработка пользовательского ввода
void handle_input(int *speed, int *running) {
    int ch = getch();  // Получаем код нажатой клавиши
    
    if (ch != ERR) {   // Если была нажата клавиша
        if (ch == ' ' || ch == 'q' || ch == 'Q') 
            *running = 0;               // Выход из игры
        
        if ((ch == 'z' || ch == 'Z') && *speed > 10000) 
            *speed -= 5000;             // Увеличить скорость (уменьшить задержку)
        
        if ((ch == 'a' || ch == 'A') && *speed < 500000) 
            *speed += 5000;             // Уменьшить скорость (увеличить задержку)
    }
}

// Основной игровой цикл
void run_game(int grid[H][W]) {
    int next[H][W];       // Буфер для следующего поколения
    int speed = 100000;   // Начальная задержка в микросекундах
    int running = 1;      // Флаг продолжения игры
    
    while (running) {
        draw(grid, speed);          // Отрисовка текущего состояния
        handle_input(&speed, &running); // Обработка ввода
        recalc(grid, next);         // Расчет следующего поколения
        usleep(speed);              // Пауза с текущей скоростью
    }
}

// Главная функция программы
int main() {
    int grid[H][W] = {0};  // Инициализация игрового поля нулями
    
    input_grid(grid);      // Загрузка начальной конфигурации
    
    // Перенаправляем stdin обратно на терминал после чтения конфигурации
    if (freopen("/dev/tty", "r", stdin)) {
        init_game();       // Инициализация ncurses
        run_game(grid);    // Запуск игры
        endwin();          // Завершение работы с ncurses
    }
    
    return 0;              // Выход из программы
}